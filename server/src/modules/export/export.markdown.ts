import { AIAnalysis } from '../ai/ai.types';
import { RepositoryMetadata } from '../github/github.types';

function listSection(title: string, items: string[]): string {
  if (items.length === 0) return '';
  return `\n## ${title}\n\n${items.map((item) => `- ${item}`).join('\n')}\n`;
}

export function buildMarkdownExport(metadata: RepositoryMetadata, analysis: AIAnalysis): string {
  return `# ${metadata.fullName}

${metadata.description ?? 'No description provided.'}

**Stars:** ${metadata.stars} | **Forks:** ${metadata.forks} | **Open Issues:** ${metadata.openIssues}
**Primary Language:** ${metadata.primaryLanguage ?? 'Unknown'}
**License:** ${metadata.license ?? 'None'}
**URL:** ${metadata.url}

## Summary

${analysis.summary}

## Purpose

${analysis.purpose}

## Architecture

${analysis.architecture}

## Folder Structure

${analysis.folderStructure}

## Installation

${analysis.installation}

**Difficulty:** ${analysis.difficulty}
${listSection('Technologies', analysis.technologies)}${listSection('Frameworks', analysis.frameworks)}${listSection('Dependencies', analysis.dependencies)}${listSection('Advantages', analysis.advantages)}${listSection('Disadvantages', analysis.disadvantages)}${listSection('Best Practices', analysis.bestPractices)}${listSection('Suggested Improvements', analysis.improvements)}${listSection('Learning Roadmap', analysis.roadmap)}${listSection('Career Skills', analysis.careerSkills)}${listSection('Target Users', analysis.targetUsers)}
---
*Generated by AI GitHub Repository Assistant*
`;
}