import PDFDocument from 'pdfkit';
import { AIAnalysis } from '../ai/ai.types';
import { RepositoryMetadata } from '../github/github.types';

function addListSection(doc: PDFKit.PDFDocument, title: string, items: string[]): void {
  if (items.length === 0) return;

  doc.moveDown(0.6);
  doc.fontSize(13).fillColor('#0f172a').text(title, { underline: false });
  doc.moveDown(0.2);
  doc.fontSize(10).fillColor('#334155');
  items.forEach((item) => {
    doc.text(`\u2022 ${item}`, { indent: 12 });
  });
}

function addTextSection(doc: PDFKit.PDFDocument, title: string, body: string): void {
  doc.moveDown(0.6);
  doc.fontSize(13).fillColor('#0f172a').text(title);
  doc.moveDown(0.2);
  doc.fontSize(10).fillColor('#334155').text(body, { align: 'left' });
}

export async function buildPdfExport(
  metadata: RepositoryMetadata,
  analysis: AIAnalysis,
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks: Buffer[] = [];

    doc.on('data', (chunk: Buffer) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', (error: Error) => reject(error));

    doc.fontSize(20).fillColor('#0f172a').text(metadata.fullName, { align: 'left' });
    doc.moveDown(0.3);
    doc
      .fontSize(10)
      .fillColor('#64748b')
      .text(metadata.description ?? 'No description provided.');

    doc.moveDown(0.6);
    doc
      .fontSize(10)
      .fillColor('#334155')
      .text(
        `Stars: ${metadata.stars}    Forks: ${metadata.forks}    Open Issues: ${metadata.openIssues}    Difficulty: ${analysis.difficulty}`,
      );
    doc.text(`Primary Language: ${metadata.primaryLanguage ?? 'Unknown'}    License: ${metadata.license ?? 'None'}`);
    doc.fillColor('#3b6cf6').text(metadata.url, { link: metadata.url, underline: true });
    doc.fillColor('#334155');

    addTextSection(doc, 'Summary', analysis.summary);
    addTextSection(doc, 'Purpose', analysis.purpose);
    addTextSection(doc, 'Architecture', analysis.architecture);
    addTextSection(doc, 'Folder Structure', analysis.folderStructure);
    addTextSection(doc, 'Installation', analysis.installation);

    addListSection(doc, 'Technologies', analysis.technologies);
    addListSection(doc, 'Frameworks', analysis.frameworks);
    addListSection(doc, 'Dependencies', analysis.dependencies);
    addListSection(doc, 'Advantages', analysis.advantages);
    addListSection(doc, 'Disadvantages', analysis.disadvantages);
    addListSection(doc, 'Best Practices', analysis.bestPractices);
    addListSection(doc, 'Suggested Improvements', analysis.improvements);
    addListSection(doc, 'Learning Roadmap', analysis.roadmap);
    addListSection(doc, 'Career Skills', analysis.careerSkills);
    addListSection(doc, 'Target Users', analysis.targetUsers);

    doc.moveDown(1);
    doc.fontSize(8).fillColor('#94a3b8').text('Generated by AI GitHub Repository Assistant', {
      align: 'center',
    });

    doc.end();
  });
}